#include <iostream>

using namespace std;

int main()
{
    // ==================================================
    // ЗАВДАННЯ 1
    // Дано відстань у кілометрах.
    // Потрібно перевести її в метри та сантиметри.
    // ==================================================

    cout << "===== ЗАВДАННЯ 1 =====" << endl;

    // Змінна для збереження відстані в кілометрах
    double km;

    // Введення відстані від користувача
    cout << "Введіть відстань у кілометрах: ";
    cin >> km;

    // Переведення кілометрів у метри
    // 1 км = 1000 м
    double meters = km * 1000;

    // Переведення кілометрів у сантиметри
    // 1 км = 100000 см
    double centimeters = km * 100000;

    // Виведення результатів на екран
    cout << "Відстань у метрах: " << meters << " м" << endl;
    cout << "Відстань у сантиметрах: " << centimeters << " см" << endl;


    // ==================================================
    // ЗАВДАННЯ 2
    // Дано рівнобедрений трикутник із основою b
    // та бічною стороною a.
    // Потрібно знайти його периметр.
    // ==================================================

    cout << endl;
    cout << "===== ЗАВДАННЯ 2 =====" << endl;

    // Змінні для збереження довжин сторін трикутника
    double a, b;

    // Введення довжини бічної сторони
    cout << "Введіть довжину бічної сторони a: ";
    cin >> a;

    // Введення довжини основи
    cout << "Введіть довжину основи b: ";
    cin >> b;

    // Формула периметра рівнобедреного трикутника:
    // P = a + a + b
    // або P = 2 * a + b
    double perimeter = 2 * a + b;

    // Виведення периметра
    cout << "Периметр трикутника: " << perimeter << endl;


    // ==================================================
    // ЗАВДАННЯ 3
    // Розв'язати лінійне рівняння Ax + B = 0.
    // За умовою коефіцієнт A не дорівнює 0.
    // ==================================================

    cout << endl;
    cout << "===== ЗАВДАННЯ 3 =====" << endl;

    // Змінні для коефіцієнтів рівняння та його розв'язку
    double A, B, x;

    // Введення коефіцієнта A
    cout << "Введіть коефіцієнт A (A не дорівнює 0): ";
    cin >> A;

    // Введення коефіцієнта B
    cout << "Введіть коефіцієнт B: ";
    cin >> B;

    // Розв'язання рівняння Ax + B = 0.
    // Переносимо B в праву частину:
    // Ax = -B
    // Ділимо обидві частини на A:
    // x = -B / A
    x = -B / A;

    // Виведення знайденого значення x
    cout << "Розв'язок рівняння: x = " << x << endl;

    // Завершення роботи програми
    return 0;
}
